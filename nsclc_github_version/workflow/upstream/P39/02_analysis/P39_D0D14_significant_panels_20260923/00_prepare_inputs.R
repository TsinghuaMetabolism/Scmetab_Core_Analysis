# Freeze P39 inputs for panels a-e while replacing all trajectory-dependent
# fields with the D0/D14-only significant-feature trajectory.
suppressPackageStartupMessages(library(data.table))
a <- grep('^--file=',commandArgs(FALSE),value=TRUE)
root <- dirname(normalizePath(sub('^--file=','',a[1])))
source_root <- normalizePath(file.path(root,'../P39_complete_20260922'))
out <- file.path(source_root,'trajectory_review/anchor_consistent_sensitivity')

m <- fread(file.path(source_root,'tables/cell_annotations.csv'))
t <- fread(file.path(out,'cell_trajectory.csv'))
s <- fread(file.path(out,'cell_stage.csv'))
e <- fread(file.path(out,'trajectory_edges.csv'))
screen <- fread(file.path(out,'feature_selection.csv'))
stopifnot(nrow(m)==1068L,nrow(t)==1068L,nrow(s)==1068L,
          setequal(m$cell_id,t$cell_id),setequal(m$cell_id,s$cell_id),
          sum(screen$selected)==159L,all(screen$selected==screen$eligible),
          uniqueN(t$state)==1L,!anyNA(m$cell_type),all(nzchar(m$cell_type)))
setkey(t,cell_id); setkey(s,cell_id)
t <- t[m$cell_id]; s <- s[m$cell_id]
stopifnot(identical(t$cell_id,m$cell_id),identical(s$cell_id,m$cell_id),
          isTRUE(all.equal(t$pseudotime,s$pseudotime)))
m[,`:=`(trajectory_1=t$trajectory_1,trajectory_2=t$trajectory_2,
         pseudotime=t$pseudotime,Monocle_state=t$state,
         progress_state=s$progress_state,trajectory_eligible=TRUE)]

dir.create(file.path(root,'panel_b/inputs'),recursive=TRUE,showWarnings=FALSE)
fwrite(m,file.path(root,'panel_b/inputs/Osi_cells_and_trajectory.csv'))
fwrite(e,file.path(root,'panel_b/inputs/fixed_reference_tree_edges.csv'))
fwrite(screen,file.path(root,'panel_b/inputs/ordering_feature_screen.csv'))

# Panel C uses treated cells only, as in the P59 panel-C association analysis.
treated <- m[day!='D0']
x <- fread(file.path(root,'panel_c/inputs/corrected_intensity.csv'))
stopifnot(setequal(x$cell_id,treated$cell_id))
setkey(x,cell_id); x <- x[treated$cell_id]
stopifnot(identical(x$cell_id,treated$cell_id),nrow(treated)==825L)
fwrite(treated,file.path(root,'panel_c/inputs/cells.csv'))
fwrite(x,file.path(root,'panel_c/inputs/corrected_intensity.csv'))
fwrite(screen,file.path(root,'panel_c/inputs/ordering_feature_screen.csv'))

# Panel D must consume the statistical family freshly generated by panel C.
# The runner copies that table after fitting. Panel E is independent of
# pseudotime; its frozen CSVs are the same corrected matrix and true-day labels.
checks <- data.table(
  check=c('retained_cells','empty_cell_type','ordering_features',
          'natural_states','treated_cells','trajectory_edges'),
  value=c(nrow(m),sum(is.na(m$cell_type)|!nzchar(m$cell_type)),
          sum(screen$selected),uniqueN(t$state),nrow(treated),nrow(e)),
  expected=c(1068,0,159,1,825,49)
)
checks[,passed:=value==expected]
fwrite(checks,file.path(root,'input_validation.csv'))
stopifnot(all(checks$passed))
cat('Prepared P39 panel inputs:',nrow(m),'cells,',nrow(treated),
    'treated cells,',sum(screen$selected),'ordering features.\n')
